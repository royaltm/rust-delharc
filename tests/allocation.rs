#[test]
fn test_oversize_allocation() {
    let _ = delharc::LhaDecodeReader::new(Cursor::new(TEST_DATA));
    let peak = PEAK.load(Ordering::Relaxed);
    eprintln!("largest single allocation requested: {peak} bytes (~{:.2} GB)", peak as f64 / 1e9);
    assert_eq!(peak, 8192);
}
